#: знает. Договорённость между людьми проверить нечем.
MEASURED_MODEL = "Qwen/Qwen2.5-7B-Instruct"
MEASURED_RUNTIME = "vllm-0.31.0"
MEASURED_DTYPE = "bfloat16"

#: Справочные величины из замеров — для проверки самого проверяющего.
#: Если демон на честной паре даёт не около HONEST_MEAN, сломан демон, а
