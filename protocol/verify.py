FRAUD_FP8_MIN = 0.03778   # самый незаметный из измеренных подлогов
FRAUD_FP8_MEAN = 0.06139


class Rejected(Exception):
    """Задание не подлежит проверке этим способом."""


@dataclass(frozen=True)
class Verdict:
    divergences: tuple
    exceeded: int
    guilty: bool

    def __str__(self):
        d = ", ".join(f"{x:.5f}" for x in self.divergences)
        return (f"{'ВИНОВЕН' if self.guilty else 'чист'}: "
                f"превысило {self.exceeded}/{len(self.divergences)} "
                f"при пороге {THRESHOLD} [{d}]")


def divergence(a, b):
    """Среднее абсолютное расхождение двух векторов вероятностей.

    None в векторе — токен, для которого вероятность не вернулась; такие
    позиции выбрасываются до сравнения, иначе расхождение считается по
    сдвинутым индексам и выходит мусор.

    Векторы сравниваются по общей длине. Разная длина сама по себе уликой
    не считается: жадное декодирование может оборваться по лимиту токенов
    в разный момент, и это не подлог.
    """
    x = [v for v in a if v is not None]
    y = [v for v in b if v is not None]
    n = min(len(x), len(y))
    if n == 0:
        raise Rejected("пустой вектор вероятностей")
    return statistics.fmean(abs(x[i] - y[i]) for i in range(n))


def check_eligible(answer_tokens, model, runtime, dtype, params=None):
    """Можно ли вообще проверять это задание. Бросает Rejected, если нет.

    params — настройки ИЗ ЦЕПОЧКИ (daemon.chain.Params). Без них
    сверяемся с замеренной связкой, и это допустимо только в тестах:
    в работе параметры обязаны приходить из цепочки, иначе демон живёт
    по своему представлению о протоколе.
    """
    min_tokens = params.min_answer_tokens if params else MIN_ANSWER_TOKENS
    want = ((params.pinned_model, params.pinned_runtime, params.pinned_dtype)
            if params else (MEASURED_MODEL, MEASURED_RUNTIME, MEASURED_DTYPE))
    if len(answer_tokens) < min_tokens:
        raise Rejected(
            f"ответ {len(answer_tokens)} токенов, нужно от {min_tokens}: "
            "на коротких ответах запас падает до 1,6x")
    if (model, runtime, dtype) != want:
        raise Rejected(
            f"связка {model}/{runtime}/{dtype} не та, для которой "
            f"действителен порог ({'/'.join(want)})")


def verdict(producer_logprobs, checker_logprobs, params=None):
    """Вердикт по четырём независимым оценкам одного и того же ответа.

    producer_logprobs — вектор исполнителя, один.
    checker_logprobs — список векторов проверяющих, по одному на проверку.

    Виновен, только если ВСЕ проверки превысили порог.
    """
    checks = params.checks_required if params else CHECKS
    thr = params.threshold_micro / 1e6 if params else THRESHOLD
    if len(checker_logprobs) != checks:
        raise Rejected(f"нужно ровно {checks} проверок, передано "
                       f"{len(checker_logprobs)}")
    ds = tuple(divergence(producer_logprobs, c) for c in checker_logprobs)
    exceeded = sum(1 for d in ds if d >= thr)
    return Verdict(divergences=ds, exceeded=exceeded, guilty=exceeded == checks)
