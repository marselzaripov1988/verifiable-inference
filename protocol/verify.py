#: Нижняя граница длины ответа. Фаза 1: ниже 32 токенов запас 1,6x.
MIN_ANSWER_TOKENS = 32

#: Связка, при которой порог был ИЗМЕРЕН. Это запись о замере, а НЕ
#: источник истины для протокола: шаг 12 перенёс параметры в настройки
#: контракта, и демон читает их оттуда (daemon/chain.py). Константы
