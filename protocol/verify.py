THRESHOLD = 0.0360

#: Сколько независимых проверок и сколько из них должны превысить порог.
#: Лучше у четырёх РАЗНЫХ проверяющих: межкарточный разброс оказался равен
#: внутрикарточному, так что разные карты ничего не портят, а сговор
#: одного так не проходит.
