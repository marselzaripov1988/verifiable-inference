use cosmwasm_schema::cw_serde;
use cosmwasm_std::{Addr, Uint128};
use cw_storage_plus::{Item, Map};

/// Расхождение хранится в МИКРОДОЛЯХ (1e-6), а не в плавающей точке:
/// на цепочке плавающей точки нет вовсе, и даже будь она — разные узлы
/// давали бы разный результат, а консенсус требует одинакового.
///
/// Порог 0,0360 это 36_000. Честное среднее 0,01270 это 12_700. Разрешения
/// хватает с огромным запасом: худшее честное и минимум подлога отличаются
/// на 6_880 микродолей.
pub type Micro = u64;

/// Вероятность в микродолях со знаком: logprob всегда отрицателен, и
/// плавающей точки на цепочке нет. -0,693147 это -693_147.
///
/// КАНОНИЧЕСКОЕ ПРЕДСТАВЛЕНИЕ для хэша: каждый элемент как i64 в
/// little-endian, восемь байт, подряд, без разделителей и без длины.
/// Демоны обязаны кодировать так же, иначе хэш не сойдётся и раскрытие
/// будет отвергнуто. Описано здесь, а не в коде демона, потому что
/// расходиться им нельзя.
pub type MicroLog = i64;

#[cw_serde]
pub struct Config {
    /// Кто может менять настройки и отстранять исполнителей.
    pub admin: Addr,
    /// Кто подтверждает допуск исполнителя.
    ///
    /// Вынесено наружу не от лени: контракт НЕ МОЖЕТ прочитать x/referral,
    /// потому что в наборе возможностей wasm у Axiome вырезан `stargate`.
    /// Значит проверку статуса делает кто-то вне контракта и сообщает
    /// результат сюда. Это ограничение площадки, и оно должно быть видно
    /// в коде, а не спрятано в договорённости.
    pub attestor: Addr,
    /// Порог среднего расхождения в микродолях. Замер: 36_000.
    pub threshold_micro: Micro,
    /// Сколько проверок нужно и сколько из них должны превысить порог.
    /// Виновен только если ВСЕ превысили. Замер: 4.
    pub checks_required: u32,
    /// Ниже этой длины ответа способ не работает (запас падает до 1,6x).
    pub min_answer_tokens: u32,
    /// Связка, для которой измерен порог. Смена любой части обнуляет
    /// порог до перезамера, поэтому это параметр консенсуса, а не
    /// договорённость: контракт отклоняет чужую связку при регистрации.
    ///
    /// НО СВЕРКИ ИМЁН НЕДОСТАТОЧНО, и это замерено: на одной карте, при
    /// той же модели, той же версии и том же dtype, `--enforce-eager`
    /// против пути по умолчанию дал ни одного побитового совпадения из
    /// 40 и среднее расхождение 49 424 — внутри полосы подлога. То есть
    /// честный узел не в том режиме исполнения выглядит жуликом, а
    /// заявленная тройка у него правильная. Поэтому связка проверяется
    /// ещё и по поведению — пробой на эталонном векторе ниже.
    pub pinned_model: String,
    pub pinned_runtime: String,
    pub pinned_dtype: String,

    // --- проба на эталонном векторе -------------------------------------
    /// Предел расхождения с эталоном. Выведен из данных: честные
    /// максимумы по текстам 19 656 (A100), 20 137 (3090) и 22 421
    /// (ДРУГОЙ 4090 против эталона, снятого на 4090), неверный режим
    /// исполнения — 410 012. Рекомендуемое значение 60 000: запас 2,7x
    /// к худшему честному наблюдению, и неверный режим всё равно
    /// превышает его в 6,8 раза.
    ///
    /// Третье наблюдение и показало, зачем это параметр: первое
    /// рекомендованное значение 25 000 оставляло запас 1,1x, и честная
    /// карта могла получить отказ. Карт, кроме замеренных, предел
    /// по-прежнему не знает.
    pub conformance_limit_micro: Micro,
    /// Обязательство эталонным набором: хэш СКЛЕЙКИ эталонных векторов в
    /// порядке пробы. Сами векторы вне цепочки — 3 948 чисел, — и это тот
    /// же приём, что с вектором задания.
    pub conformance_ref_hash: String,
    /// Длины эталонных векторов по текстам. Нужны именно на цепочке:
    /// статистика пробы — максимум ПО ТЕКСТАМ, и без длин раскрытую
    /// склейку не разрезать.
    ///
    /// Почему максимум, а не среднее по склейке: неверный режим портит
    /// РЕДКИЕ тексты (у eager 29 из 40 совпали побитово), и среднее их
    /// размывает — зазор падает с 20x до 1,5x.
    pub conformance_lens: Vec<u32>,
    /// Версия эталона. Любая смена эталона или прибитой связки её
    /// повышает, и все выданные пробы разом перестают действовать:
    /// проба свидетельствует о соответствии КОНКРЕТНОЙ настройке, и
    /// после её смены свидетельство пустое.
    pub conformance_version: u64,
    /// Чем идёт расчёт. Настройкой, а не константой в коде: BARTR на
    /// Axiome это CW20, шлюз этапа 1 собирает родной AXM, а при
    /// появлении IBC расчёт переедет на ваучер — то есть на третью
    /// единицу. Менять это должно быть правкой настройки, а не выпуском
    /// нового контракта.
    pub settlement: Settlement,
    /// Единица залога. Родная монета цепочки: её сжигание — настоящая
    /// стока, в отличие от сжигания CW20.
    pub stake_denom: String,

    // --- деньги (шаг 14) ------------------------------------------------
    /// Минимальный залог. Замер: кратно суточной выручке карты, один-семь
    /// суток, то есть $38–265 по порогу безубыточности. Числом здесь, а
    /// не формулой: курс едет, и перепривязка — дело governance.
    pub min_stake: Uint128,
    /// Доля проверяющих от цены задания, в базисных пунктах.
    ///
    /// РЕШЕНИЕ НЕ ПРИНЯТО, и принимать его не мне: замер говорит, что
    /// проверка стоит 9,7% от порождения при четырёх проверках, но КТО
    /// их платит — заказчик, исполнитель или сеть — это выбор, а не
    /// измерение. Здесь параметр, чтобы выбор был виден и обратим.
    /// 970 bps = 9,7% — ровно замеренные накладные.
    pub verifier_fee_bps: u16,
    /// Куда уходит изъятый залог.
    pub forfeit: Forfeit,
}

#[cw_serde]
pub enum Settlement {
    /// Родная монета цепочки. Платёж приходит С ТРАНЗАКЦИЕЙ, выплаты
    /// идут BankMsg::Send.
    ///
    /// Это то, что собирает шлюз этапа 1, и в этом смысл варианта: иначе
    /// этап 1 считает в AXM, а протокол в CW20, и расхождение придётся
    /// объяснять каждому владельцу карты.
    Native(String),
    /// Контракт CW20. Платёж приходит только через Receive — Send на
    /// контракт с вложенным сообщением, — а выплаты через
    /// WasmMsg::Execute{transfer}. Нужен для BARTR, который CW20, и это
    /// цена того выбора, о котором предупреждал шаг 8.
    Cw20(Addr),
}

impl Settlement {
    /// Имя единицы для вывода и для сверки демонами.
    pub fn label(&self) -> String {
        match self {
            Settlement::Native(d) => d.clone(),
            Settlement::Cw20(a) => format!("cw20:{a}"),
        }
    }
}

#[cw_serde]
pub enum Forfeit {
    /// Сжечь. Настоящая стока: AXM родной для Axiome, монета исчезает.
    ///
    /// Опирается на BankMsg::Burn, а он требует поддержки от цепочки.
    /// Против Axiome это не проверено, поэтому и оставлен второй вариант.
    Burn,
    /// Отдать по адресу. Заказчику, которому отдали плохой ответ, либо
    /// в общий пул.
    ///
    /// Чего здесь нет намеренно: варианта «проверяющим». Если конфискат
    /// идёт обвинявшим, у них появляется прямой интерес обвинять.
    /// Ложное обвинение честного у нас 4,8e-11 на проверку, то есть
    /// случайно этого не бывает — но сговор это другая угроза, и
    /// платить им из конфиската значит создать её своими руками.
    ToAddress(Addr),
}

#[cw_serde]
pub enum ExecutorStatus {
    /// Зарегистрировался, допуск не подтверждён. Заданий не получает.
    Pending,
    /// Допущен, может брать задания.
    Active,
    /// Отстранён администратором. Обратимо.
    Suspended,
    /// Пойман на подлоге. Необратимо.
    Banned,
}

#[cw_serde]
pub struct Executor {
    pub model: String,
    pub runtime: String,
    pub dtype: String,
    /// Класс карты — справочно. Протокол его НЕ использует для допуска:
    /// замерено, что межкарточный разброс равен внутрикарточному, то есть
    /// требовать одинаковых карт не нужно.
    pub card_class: String,
    pub status: ExecutorStatus,
    pub jobs_done: u64,
    pub convictions: u64,
    /// Внесённый залог в stake_denom. Активным исполнитель становится
    /// только при залоге не ниже min_stake.
    pub stake: Uint128,
    /// Пройденная проба на эталонном векторе. None — заданий не получает,
    /// сколько бы ни было залога и допуска: заявленная связка ничего не
    /// говорит о режиме исполнения.
    pub conformance: Option<Conformance>,
}

#[cw_serde]
pub struct Conformance {
    /// Максимум среднего расхождения с эталоном ПО ТЕКСТАМ пробы.
    pub divergence_micro: Micro,
    /// Обязательство СВОИМИ векторами пробы: хэш склейки в порядке пробы.
    ///
    /// Без него число было бы словом исполнителя о самом себе: посчитать
    /// расхождение он может сам и назвать любое. С обязательством любой
    /// раскрывает оба набора и пересчитывает — так же, как со спором по
    /// заданию.
    pub logprobs_hash: String,
    /// Против какой версии эталона считалось.
    pub ref_version: u64,
}

#[cw_serde]
pub enum JobState {
    /// Создано, исполнитель не назначен.
    Open,
    /// Исполнитель взял задание.
    Claimed,
    /// Ответ сдан, собираются проверки.
    Answered,
    /// Вердикт вынесен.
    Settled,
}

#[cw_serde]
pub struct Job {
    pub client: Addr,
    pub prompt_hash: String,
    pub executor: Option<Addr>,
    pub state: JobState,
    /// Хэш ответа и хэш вектора вероятностей. Сам вектор на цепочку не
    /// кладётся: это ~120 чисел на ответ. Раскрывается при споре, и
    /// порядок безопасен сам собой — исполнитель публикует первым и не
    /// знает результата проверяющих.
    pub answer_hash: Option<String>,
    pub logprobs_hash: Option<String>,
    pub answer_tokens: Option<u32>,
    /// Итог: виновен или нет. None пока не вынесен.
    pub guilty: Option<bool>,
    /// Раскрывался ли вектор исполнителя и сошёлся ли он с хэшем.
    pub reveal_verified: Option<bool>,
    /// Цена задания в единице расчёта, уже полученная контрактом.
    pub price: Uint128,
    /// Выплачено ли по заданию. Защита от двойной выплаты.
    pub paid: bool,
}

#[cw_serde]
pub struct Check {
    pub checker: Addr,
    pub divergence_micro: Micro,
    /// Хэш вектора проверяющего. Без него расхождение — слово
    /// проверяющего против слова исполнителя, и оспорить его нечем.
    pub logprobs_hash: String,
    /// Итог спора: расхождение пересчитано и совпало с заявленным.
    /// None — спора не было.
    pub honest: Option<bool>,
}

pub const CONFIG: Item<Config> = Item::new("config");
pub const EXECUTORS: Map<&Addr, Executor> = Map::new("executors");
pub const JOBS: Map<u64, Job> = Map::new("jobs");
pub const NEXT_JOB: Item<u64> = Item::new("next_job");
/// Проверки по заданию: (job_id, checker) -> Check.
/// Ключ с адресом внутри не даёт одному проверяющему сдать две проверки
/// на одно задание — иначе четыре «независимые» проверки мог бы сдать
/// один, и всё правило обессмысливается.
pub const CHECKS: Map<(u64, &Addr), Check> = Map::new("checks");
