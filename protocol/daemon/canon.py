#!/usr/bin/env python3
"""Канон кодирования. Обязан совпадать с контрактом ПОБАЙТОВО.

Контракт пересчитывает расхождение сам (ResolveDispute), значит обе
стороны должны получать из одного вектора одни и те же байты и одно и то
же число. Любое расхождение здесь означает, что честный исполнитель
окажется обвинён, а его раскрытие — отвергнуто.

Поэтому в test_canon.py лежат ЭТАЛОННЫЕ хэши, снятые с реализации на
Rust. Rust здесь авторитет: он работает на цепочке, а этот файл должен
под него подстраиваться, не наоборот.

Источник канона — protocol/contract/src/contract.rs, commit_hash:
каждый элемент как i64 little-endian, восемь байт, подряд, без длины и
без разделителей.
"""

import hashlib

#: Множитель перевода logprob в целые. Должен совпадать с MicroLog в
#: контракте: -0,693147 это -693_147.
MICRO = 1_000_000


class EmptyVector(Exception):
    """Пустой вектор. Отдельная ошибка, а не ноль."""


def to_micro(logprobs):
    """Вещественные logprob в целые микродоли.

    Округление к ближайшему, а не усечение: усечение systematically
    сдвигало бы все значения в одну сторону, и расхождение двух честных
    узлов выросло бы на половину микродоли на каждом токене просто от
    способа округления.

    None — токен, для которого вероятность не вернулась. Такие позиции
    ВЫБРАСЫВАЮТСЯ, а не заменяются нулём: ноль это осмысленная
    вероятность, и подстановка исказила бы расхождение.
    """
    return [int(round(x * MICRO)) for x in logprobs if x is not None]


def encode(v):
    """Канонические байты вектора. См. docstring модуля."""
    out = bytearray()
    for x in v:
        if not -(2**63) <= x < 2**63:
            raise ValueError(f"{x} не влезает в i64")
        out += int(x).to_bytes(8, "little", signed=True)
    return bytes(out)


def commit_hash(v):
    """Обязательство вектором: sha256 канонических байтов, hex в нижнем.

    ОСТОРОЖНО: пустой вектор даёт e3b0c442…b855 — sha256 пустой строки.
    Это осмысленный хэш, и сам по себе он ничего не ловит. Именно этой
    суммой подписывались две пустые выгрузки состояния, которые я принял
    за успешные репетиции отката. Контракт отвергает пустой вектор при
    пересчёте расхождения, но на этапе сверки хэша он пройдёт — значит
    пустоту надо проверять отдельно, и это делает require_nonempty.
    """
    return hashlib.sha256(encode(v)).hexdigest()


def require_nonempty(v):
    if not v:
        raise EmptyVector("пустой вектор вероятностей")
    return v


def divergence_micro(a, b):
    """Среднее абсолютное расхождение в микродолях.

    Деление целочисленное вниз — как в контракте. Округление вниз
    работает в пользу исполнителя: лучше пропустить на границе, чем
    обвинить честного.

    Разная длина уликой не считается: жадное декодирование может
    оборваться по лимиту токенов в разный момент. Сравнивается общая
    часть.
    """
    n = min(len(a), len(b))
    if n == 0:
        raise EmptyVector("пустой вектор вероятностей")
    return sum(abs(a[i] - b[i]) for i in range(n)) // n
