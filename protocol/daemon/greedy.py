"""Жадная проверка: тот ли модель породил текст, что объявлен.

Хэш вероятностей ловит узел, который ОЦЕНИЛ текст не так. Но откуда взят
сам текст, он не видит: узел может породить ответ дешёвой моделью и
честно оценить его эталонной — хэши у всех сойдутся. Жадное порождение
оставляет след: в каждой позиции стоит самый вероятный токен. Значит,
по тому же одному проходу оценки видно, сколько токенов ответа эталонная
модель на своём месте не выбрала бы и насколько.

Замер 11 ноября 2026 (4090, Qwen2.5-7B-Instruct, 32 вопроса, генерация
без штрафа за повтор, `zapisi/zhadnost-2026-11-11`). Правило «не меньше
3 токенов с разрывом больше 0,5» поймало:

    честные ответы, по одному / по 8 / по 32 разом    0, 0, 0 из 32
    выборка T=0,7 / T=1,0                             29, 28
    Qwen2.5-1.5B / 3B                                 31, 30
    та же 7B в AWQ 4 бита                             27
    та же 7B в FP8                                    1

Единичные разрывы до 4,3 у честных ответов бывают — по одному-два на
ответ: текст при оценке разбивается на токены чуть иначе, чем его
породили. Поэтому мерило — число таких токенов, а не наибольший разрыв.

**Пока только журнал.** Вердикт записывается и печатается, но в цепочку
не идёт и на хэш не влияет: 32 ответа на один класс — мало, чтобы по
этому порогу отнимать залог. Порог уточняется по журналу живых заданий.
"""

import vllm_client as vllm

#: Разрыв, выше которого токен считается «не своим», в долях натурального
#: логарифма. Честные ответы: 0,28% токенов с разрывом больше нуля, почти
#: все — 0,125 и 0,25 (шаг bf16).
GAP = 0.5

#: Сколько «не своих» токенов делают ответ подозрительным.
MIN_TOKENS = 3

#: Сколько лучших вариантов просить на позицию. Нужен только первый, но
#: vLLM отдаёт лучший лишь в составе top-k, а выбранный токен может в него
#: и не войти.
TOP_K = 5


def gaps(base, model, prompt, answer):
    """Разрыв каждого токена ответа с лучшим в его позиции, ≥ 0.

    Позиции ответа отсчитываются от длины отдельно оценённого промпта.
    Если склейка на стыке промпта и ответа разбилась иначе, первый токен
    ответа будет посчитан неточно — правило «не меньше трёх» это терпит.
    """
    n_prompt = len(vllm.echo(base, model, prompt, 1)["tokens"])
    e = vllm.echo(base, model, prompt + answer, TOP_K)
    out = []
    for chosen, top in list(zip(e["token_logprobs"],
                                e["top_logprobs"]))[n_prompt:]:
        if chosen is None or not top:
            continue
        out.append(max(0.0, max(top.values()) - chosen))
    return out


def verdict(g):
    """Сводка по разрывам. `suspect` — ответ не похож на жадный."""
    bad = sum(x > GAP for x in g)
    return {
        "tokens": len(g),
        "over_gap": bad,
        "max_gap": round(max(g), 3) if g else 0.0,
        "suspect": bad >= MIN_TOKENS,
        "rule": f">= {MIN_TOKENS} tokens with gap > {GAP}",
    }


def check(base, model, prompt, answer):
    """Вердикт по паре или None, если узел не ответил. Никогда не бросает:
    жадная проверка не должна мешать основной."""
    try:
        return verdict(gaps(base, model, prompt, answer))
    except vllm.NODE_FAILURES:
        return None
    except (KeyError, TypeError, ValueError):
        return None
